import java.util.*;
import java.io.*;

class Codechef {
    public static void main(String[] args) throws IOException {
        Scanner sc = new Scanner(System.in);
        int T = sc.nextInt();

        while (T-- > 0) {
            long N = sc.nextLong();
            System.out.println(N - 1);
        }

        sc.close();
    }
}
